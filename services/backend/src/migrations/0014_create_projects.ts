import { Effect } from "effect";
import { SqlClient } from "effect/sql";

/**
 * The projects page: one row per project of the site owner, with links to
 * its source code and to the project itself.
 *
 * Admins write projects in place with the same editor and document format
 * as blog posts, and upload their images to media with scope `projects`
 * (0013).
 *
 * The checks mirror the contract (lib/api `domain/Project.ts`) with the
 * conventions of 0013: lengths by char_length (code points, never more than
 * the contract's UTF-16 count), "trimmed" as no leading or trailing ASCII
 * whitespace, tags by blog_posts_tags_valid, and timestamps without
 * defaults, set by the application from the Effect clock.
 */
export default Effect.gen(function* () {
  const sql = yield* SqlClient.SqlClient;

  // id is generated by the application (UUID v4). slug is the public name
  // in URLs (`GET /projects/:project`), with the pattern and length of the
  // blog slugs; unlike blogs.slug it may change, since nothing refers to it
  // by value. Its unique index serves the lookup by slug.
  //
  // title (1 to 120) and summary (0 to 500) are trimmed. tags follow the
  // rules of post tags (at most 10, see blog_posts_tags_valid in 0013).
  //
  // status describes the project, not its visibility; published decides
  // whether it is listed. featured projects come first in the listing, then
  // by position (0 to 10000, chosen by the admin), then last saved first.
  //
  // repo_url and live_url are absolute http(s) URLs of at most 2048
  // characters. The application validates them fully; the database only
  // checks the scheme prefix (lowercase, as the URL standard prints it) and
  // the length.
  //
  // content is the TipTap document, checked like blog_posts.content: the
  // root must be an object with `"type": "doc"`.
  //
  // cover_media_id is an image of media; deleting the image removes it as
  // cover. created_by and updated_by are the admins who created and last
  // saved the project, NULL for accounts deleted since. None of the three
  // has an index: images and users are deleted rarely, and the SET NULL
  // then scans this small table.
  //
  // version counts saves, for optimistic locking, like blog_posts.version.
  //
  // `\\t` etc. are escaped for the template literal: Postgres receives `\t`.
  yield* sql`
    CREATE TABLE projects (
      id uuid NOT NULL,
      slug text NOT NULL,
      title text NOT NULL,
      summary text NOT NULL,
      tags text[] NOT NULL DEFAULT '{}',
      status text NOT NULL,
      featured boolean NOT NULL DEFAULT false,
      position integer NOT NULL DEFAULT 0,
      repo_url text NULL,
      live_url text NULL,
      cover_media_id uuid NULL,
      content jsonb NOT NULL,
      published boolean NOT NULL DEFAULT false,
      created_by uuid NULL,
      updated_by uuid NULL,
      created_at timestamptz NOT NULL,
      updated_at timestamptz NOT NULL,
      version integer NOT NULL DEFAULT 1,
      CONSTRAINT projects_id_pkey PRIMARY KEY (id),
      CONSTRAINT projects_slug_key UNIQUE (slug),
      CONSTRAINT projects_cover_media_id_fkey FOREIGN KEY (cover_media_id)
        REFERENCES media (id) ON DELETE SET NULL,
      CONSTRAINT projects_created_by_fkey FOREIGN KEY (created_by)
        REFERENCES users (id) ON DELETE SET NULL,
      CONSTRAINT projects_updated_by_fkey FOREIGN KEY (updated_by)
        REFERENCES users (id) ON DELETE SET NULL,
      CONSTRAINT projects_slug_check
        CHECK (
          slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'
          AND char_length(slug) <= 64
        ),
      CONSTRAINT projects_title_check
        CHECK (
          char_length(title) BETWEEN 1 AND 120
          AND title !~ '^[ \\t\\n\\v\\f\\r]|[ \\t\\n\\v\\f\\r]$'
        ),
      CONSTRAINT projects_summary_check
        CHECK (
          char_length(summary) <= 500
          AND summary !~ '^[ \\t\\n\\v\\f\\r]|[ \\t\\n\\v\\f\\r]$'
        ),
      CONSTRAINT projects_tags_check
        CHECK (cardinality(tags) <= 10 AND blog_posts_tags_valid(tags)),
      CONSTRAINT projects_status_check
        CHECK (status IN ('active', 'completed', 'archived')),
      CONSTRAINT projects_position_check
        CHECK (position BETWEEN 0 AND 10000),
      CONSTRAINT projects_repo_url_check
        CHECK (repo_url ~ '^https?://' AND char_length(repo_url) <= 2048),
      CONSTRAINT projects_live_url_check
        CHECK (live_url ~ '^https?://' AND char_length(live_url) <= 2048),
      CONSTRAINT projects_content_check
        CHECK (content @> '{"type": "doc"}'),
      CONSTRAINT projects_version_check CHECK (version >= 1)
    )
  `;

  // The public listing, in its order:
  //
  //   WHERE published
  //   ORDER BY featured DESC, position, updated_at DESC, id
  //
  // Partial on published, so drafts take no space in it and the condition
  // needs no column. id makes the order total (two projects saved in the
  // same millisecond).
  yield* sql`
    CREATE INDEX projects_featured_position_updated_at_id_idx
      ON projects (featured DESC, position, updated_at DESC, id)
      WHERE published
  `;
});
