import { Effect } from "effect";
import { SqlClient } from "effect/sql";

/**
 * Food data and the AI meal planner, for Germany (`DE`, prices in `EUR`) and
 * New Zealand (`NZ`, prices in `NZD`), and the fixed role `foodPlanner`.
 *
 * - food_items: one row per food we know, per country, as a source names it
 *   (an Open Food Facts product, an Open Prices category, a Stats NZ price
 *   series).
 * - food_prices: prices of those items, observed by a source or estimated.
 *   A price is always the price of one package of the item.
 * - food_imports: the background jobs that fill both tables, triggered
 *   through the API and run by the backend.
 * - meal_plans: the plans users requested from the AI meal planner, which
 *   generates them in the background, stored per user.
 *
 * `foodPlanner` is a fixed role like `admin`: superAdmins grant and revoke
 * it through the admin API, so user_roles and user_role_changes must accept
 * it. This replaces user_roles_role_check and user_role_changes_role_check
 * (0012) under the same names, the same way 0012 did; see there for why
 * each is one statement and validated right away. The blogEditor pattern is
 * unchanged.
 *
 * The text checks count code points with char_length, which is never more
 * than the contract's UTF-16 count (see 0013). Unlike the editorial tables,
 * the texts of food_items and food_prices come from external data, so the
 * checks do not require them to be trimmed: one oddly spaced product name
 * must not fail an import. The timestamps have no defaults: the application
 * sets them from the Effect clock.
 */
export default Effect.gen(function* () {
  const sql = yield* SqlClient.SqlClient;

  // Only widens the old checks, so every existing row satisfies them.
  yield* sql`
    ALTER TABLE user_roles
      DROP CONSTRAINT user_roles_role_check,
      ADD CONSTRAINT user_roles_role_check
        CHECK (
          role IN ('normalUser', 'admin', 'superAdmin', 'foodPlanner')
          OR (
            role ~ '^blogEditor:[a-z0-9]+(-[a-z0-9]+)*$'
            AND char_length(role) <= 75
          )
        )
  `;
  yield* sql`
    ALTER TABLE user_role_changes
      DROP CONSTRAINT user_role_changes_role_check,
      ADD CONSTRAINT user_role_changes_role_check
        CHECK (
          role IN ('normalUser', 'admin', 'superAdmin', 'foodPlanner')
          OR (
            role ~ '^blogEditor:[a-z0-9]+(-[a-z0-9]+)*$'
            AND char_length(role) <= 75
          )
        )
  `;

  // One row per food and country. id is generated by the application
  // (UUID v4).
  //
  // (country, source, source_ref) identifies the item at its source, so a
  // re-import updates the row instead of adding one (upserts use
  // food_items_country_source_source_ref_key; keep the name stable).
  // source_ref is a barcode (`openFoodFacts`), a category tag like
  // `en:apples` (`openPricesCategory`) or a Stats NZ series like
  // `CPIM.SAP0101` (`statsNz`). Neither the country nor the source of an
  // item changes; a different one is a different item.
  //
  // quantity_amount and quantity_unit are the package size, both set or
  // both unknown (food_items_quantity_check); the amount is positive.
  //
  // vegetarian and vegan are NULL when the source does not say. Each is
  // independent, except that a vegan item cannot be known as not
  // vegetarian (food_items_vegan_check): `vegan AND vegetarian IS FALSE`
  // is NULL, and so passes, whenever vegan is unknown.
  //
  // categories, ingredients and allergens are tags as the source names
  // them (`en:apples`, `en:gluten`), empty when unknown. No NULL elements:
  // array_position finds NULL with IS NOT DISTINCT FROM.
  yield* sql`
    CREATE TABLE food_items (
      id uuid NOT NULL,
      country text NOT NULL,
      source text NOT NULL,
      source_ref text NOT NULL,
      name text NOT NULL,
      brand text NULL,
      quantity_amount numeric NULL,
      quantity_unit text NULL,
      vegetarian boolean NULL,
      vegan boolean NULL,
      categories text[] NOT NULL DEFAULT '{}',
      ingredients text[] NOT NULL DEFAULT '{}',
      allergens text[] NOT NULL DEFAULT '{}',
      created_at timestamptz NOT NULL,
      updated_at timestamptz NOT NULL,
      CONSTRAINT food_items_id_pkey PRIMARY KEY (id),
      CONSTRAINT food_items_country_source_source_ref_key
        UNIQUE (country, source, source_ref),
      CONSTRAINT food_items_country_check CHECK (country IN ('DE', 'NZ')),
      CONSTRAINT food_items_source_check
        CHECK (source IN ('openFoodFacts', 'openPricesCategory', 'statsNz')),
      CONSTRAINT food_items_source_ref_check
        CHECK (char_length(source_ref) BETWEEN 1 AND 200),
      CONSTRAINT food_items_name_check
        CHECK (char_length(name) BETWEEN 1 AND 300),
      CONSTRAINT food_items_brand_check CHECK (char_length(brand) <= 200),
      CONSTRAINT food_items_quantity_amount_check
        CHECK (quantity_amount > 0),
      CONSTRAINT food_items_quantity_unit_check
        CHECK (quantity_unit IN ('g', 'ml', 'piece')),
      CONSTRAINT food_items_quantity_check
        CHECK ((quantity_amount IS NULL) = (quantity_unit IS NULL)),
      CONSTRAINT food_items_vegan_check
        CHECK (NOT (vegan AND vegetarian IS FALSE)),
      CONSTRAINT food_items_categories_check
        CHECK (array_position(categories, NULL) IS NULL),
      CONSTRAINT food_items_ingredients_check
        CHECK (array_position(ingredients, NULL) IS NULL),
      CONSTRAINT food_items_allergens_check
        CHECK (array_position(allergens, NULL) IS NULL)
    )
  `;

  // The listing and search of one country's items:
  //
  //   WHERE country = $1 [AND name ILIKE '%term%']
  //   ORDER BY lower(name), id
  //
  // A leading-wildcard ILIKE can't use a btree, so the search scans the
  // country's rows (tens of thousands) in this index's order and stops at
  // the page limit. A trigram index would serve it directly, but pg_trgm
  // is not available in PGlite, which the tests use. id makes the order
  // total, so that pages don't overlap when names repeat. A query must
  // order by exactly `lower(name), id` to use the index for its order.
  yield* sql`
    CREATE INDEX food_items_country_lower_name_id_idx
      ON food_items (country, lower(name), id)
  `;

  // Prices of an item. id is generated by the database, like
  // user_role_changes.id.
  //
  // (food_item_id, source, source_ref) identifies a price at its source, so
  // re-importing it updates the row (upserts use
  // food_prices_food_item_id_source_source_ref_key; keep the name stable).
  // source_ref is an Open Prices price id (`openPrices`), a series and
  // month like `CPIM.SAP0101:2026.09` (`statsNz`), or `estimate`: an item
  // has at most one estimate (food_prices_estimate_check), replaced in
  // place when it is estimated again. The unique index also serves the
  // CASCADE on deleting an item.
  //
  // amount is the price of one package in currency, which is the currency
  // of the item's country; that needs a look at food_items (a trigger), so
  // the application guarantees it. accuracy (0 to 100) is the accuracy when
  // observed; the backend lowers it with the age of observed_on when it
  // reads. where_text says where the price was seen or how it was
  // estimated, for display.
  yield* sql`
    CREATE TABLE food_prices (
      id bigint GENERATED ALWAYS AS IDENTITY,
      food_item_id uuid NOT NULL,
      source text NOT NULL,
      source_ref text NOT NULL,
      amount numeric(12, 2) NOT NULL,
      currency text NOT NULL,
      observed_on date NOT NULL,
      accuracy smallint NOT NULL,
      discounted boolean NOT NULL DEFAULT false,
      where_text text NOT NULL,
      created_at timestamptz NOT NULL,
      CONSTRAINT food_prices_id_pkey PRIMARY KEY (id),
      CONSTRAINT food_prices_food_item_id_source_source_ref_key
        UNIQUE (food_item_id, source, source_ref),
      CONSTRAINT food_prices_food_item_id_fkey FOREIGN KEY (food_item_id)
        REFERENCES food_items (id) ON DELETE CASCADE,
      CONSTRAINT food_prices_source_check
        CHECK (source IN ('openPrices', 'statsNz', 'estimate')),
      CONSTRAINT food_prices_source_ref_check
        CHECK (char_length(source_ref) BETWEEN 1 AND 200),
      CONSTRAINT food_prices_estimate_check
        CHECK (source <> 'estimate' OR source_ref = 'estimate'),
      CONSTRAINT food_prices_amount_check CHECK (amount >= 0),
      CONSTRAINT food_prices_currency_check
        CHECK (currency IN ('EUR', 'NZD')),
      CONSTRAINT food_prices_accuracy_check
        CHECK (accuracy BETWEEN 0 AND 100),
      CONSTRAINT food_prices_where_text_check
        CHECK (char_length(where_text) BETWEEN 1 AND 300)
    )
  `;

  // An item's prices, latest observation first.
  yield* sql`
    CREATE INDEX food_prices_food_item_id_observed_on_idx
      ON food_prices (food_item_id, observed_on DESC)
  `;

  // Import jobs. id is generated by the application (UUID v4). A job is
  // `queued` when requested, `running` once the backend picked it up
  // (started_at set), and `succeeded` or `failed` when it ended
  // (finished_at set, food_imports_lifecycle_check). A queued job may also
  // fail without having started. items and prices count the rows the job
  // wrote, error is a short message of a failure (at most 200 characters).
  //
  // requested_by is the user who triggered it; NULL for an account deleted
  // since. No index on it: nothing reads jobs by user, and the SET NULL on
  // deleting a user scans this small table.
  yield* sql`
    CREATE TABLE food_imports (
      id uuid NOT NULL,
      country text NOT NULL,
      source text NOT NULL,
      status text NOT NULL,
      requested_by uuid NULL,
      requested_at timestamptz NOT NULL,
      started_at timestamptz NULL,
      finished_at timestamptz NULL,
      items integer NOT NULL DEFAULT 0,
      prices integer NOT NULL DEFAULT 0,
      error text NULL,
      CONSTRAINT food_imports_id_pkey PRIMARY KEY (id),
      CONSTRAINT food_imports_requested_by_fkey FOREIGN KEY (requested_by)
        REFERENCES users (id) ON DELETE SET NULL,
      CONSTRAINT food_imports_country_check CHECK (country IN ('DE', 'NZ')),
      CONSTRAINT food_imports_source_check
        CHECK (source IN ('openPrices', 'statsNz', 'priceEstimates')),
      CONSTRAINT food_imports_status_check
        CHECK (status IN ('queued', 'running', 'succeeded', 'failed')),
      CONSTRAINT food_imports_lifecycle_check
        CHECK (
          (status IN ('succeeded', 'failed')) = (finished_at IS NOT NULL)
          AND (status <> 'running' OR started_at IS NOT NULL)
          AND (started_at IS NULL OR started_at >= requested_at)
          AND (
            finished_at IS NULL
            OR finished_at >= coalesce(started_at, requested_at)
          )
        ),
      CONSTRAINT food_imports_items_check CHECK (items >= 0),
      CONSTRAINT food_imports_prices_check CHECK (prices >= 0),
      CONSTRAINT food_imports_error_check CHECK (char_length(error) <= 200)
    )
  `;

  // At most one active (queued or running) job per country and source.
  // Requesting another one while it runs violates this index, which the
  // backend maps to a 409; keep the name stable.
  yield* sql`
    CREATE UNIQUE INDEX food_imports_active_key
      ON food_imports (country, source)
      WHERE status IN ('queued', 'running')
  `;

  // The list of jobs, newest first.
  yield* sql`
    CREATE INDEX food_imports_requested_at_idx
      ON food_imports (requested_at DESC)
  `;

  // Meal plans. id is generated by the application (UUID v4). A plan
  // belongs to the user who requested it and goes with the account.
  //
  // Plans are generated in the background. A plan is `pending` from the
  // request on, then `ready` or `failed` (finished_at set):
  //
  // - pending: no result yet, so plan, finished_at and failure_reason are
  //   NULL (meal_plans_pending_check).
  // - ready: plan, total_cost, estimated_share, accuracy, model and
  //   finished_at are set and failure_reason is NULL, and a row with all of
  //   that is ready (meal_plans_ready_check, both directions).
  // - failed: failure_reason and finished_at are set
  //   (meal_plans_failed_check). The result columns may hold what the
  //   planner got to, for example the rejected plan of `invalidPlan`.
  //
  // currency is the currency of country, EUR for DE and NZD for NZ
  // (meal_plans_country_currency_check; no separate list of currencies).
  // request is what the user asked for and plan what the model answered
  // (days, shopping list, notes), both as the contract encodes them: JSON
  // objects. total_cost is the cost of the shopping list in currency,
  // cheapest_total the cheapest total the planner found for the request,
  // when known (it tells an `overBudget` plan how far off the budget is),
  // estimated_share the percentage of the cost that rests on estimated
  // rather than observed prices, and accuracy the overall accuracy (0 to
  // 100). model names the AI model that generated the plan.
  yield* sql`
    CREATE TABLE meal_plans (
      id uuid NOT NULL,
      user_id uuid NOT NULL,
      country text NOT NULL,
      currency text NOT NULL,
      status text NOT NULL,
      request jsonb NOT NULL,
      plan jsonb NULL,
      total_cost numeric(12, 2) NULL,
      cheapest_total numeric(12, 2) NULL,
      estimated_share smallint NULL,
      accuracy smallint NULL,
      model text NULL,
      failure_reason text NULL,
      created_at timestamptz NOT NULL,
      finished_at timestamptz NULL,
      CONSTRAINT meal_plans_id_pkey PRIMARY KEY (id),
      CONSTRAINT meal_plans_user_id_fkey FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE CASCADE,
      CONSTRAINT meal_plans_country_check CHECK (country IN ('DE', 'NZ')),
      CONSTRAINT meal_plans_country_currency_check
        CHECK (
          (country = 'DE' AND currency = 'EUR')
          OR (country = 'NZ' AND currency = 'NZD')
        ),
      CONSTRAINT meal_plans_status_check
        CHECK (status IN ('pending', 'ready', 'failed')),
      CONSTRAINT meal_plans_request_check
        CHECK (jsonb_typeof(request) = 'object'),
      CONSTRAINT meal_plans_plan_check CHECK (jsonb_typeof(plan) = 'object'),
      CONSTRAINT meal_plans_total_cost_check CHECK (total_cost >= 0),
      CONSTRAINT meal_plans_cheapest_total_check CHECK (cheapest_total >= 0),
      CONSTRAINT meal_plans_estimated_share_check
        CHECK (estimated_share BETWEEN 0 AND 100),
      CONSTRAINT meal_plans_accuracy_check CHECK (accuracy BETWEEN 0 AND 100),
      CONSTRAINT meal_plans_model_check
        CHECK (char_length(model) BETWEEN 1 AND 100),
      CONSTRAINT meal_plans_failure_reason_check
        CHECK (
          failure_reason IN (
            'noCandidates', 'overBudget', 'invalidPlan', 'plannerFailed'
          )
        ),
      CONSTRAINT meal_plans_finished_at_check
        CHECK (finished_at >= created_at),
      CONSTRAINT meal_plans_pending_check
        CHECK (
          status <> 'pending'
          OR (plan IS NULL AND finished_at IS NULL AND failure_reason IS NULL)
        ),
      CONSTRAINT meal_plans_ready_check
        CHECK (
          (status = 'ready') = (
            plan IS NOT NULL
            AND total_cost IS NOT NULL
            AND estimated_share IS NOT NULL
            AND accuracy IS NOT NULL
            AND model IS NOT NULL
            AND finished_at IS NOT NULL
            AND failure_reason IS NULL
          )
        ),
      CONSTRAINT meal_plans_failed_check
        CHECK (
          status <> 'failed'
          OR (failure_reason IS NOT NULL AND finished_at IS NOT NULL)
        )
    )
  `;

  // A user's plans, newest first, and the rate limit, which counts a
  // user's plans of the last 24 hours (`user_id = $1 AND created_at > $2`).
  // Also serves the CASCADE on deleting a user.
  yield* sql`
    CREATE INDEX meal_plans_user_id_created_at_idx
      ON meal_plans (user_id, created_at DESC)
  `;
});
