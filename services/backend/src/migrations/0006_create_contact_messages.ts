import { Effect } from "effect";
import { SqlClient } from "effect/sql";

/**
 * Messages submitted through the website's contact form (`POST /contact`).
 *
 * The application stores the message and enqueues a mail about it in the
 * outbox in one transaction, so a message is never lost when the mail
 * cannot be sent right away.
 *
 * The table holds personal data: the sender's name, e-mail address and a
 * free text. A retention job must purge old rows, and nothing may log its
 * columns.
 */
export default Effect.gen(function* () {
  const sql = yield* SqlClient.SqlClient;

  // One row per submitted message. id is generated by the application
  // (UUID v4), like users.id. There are no foreign keys: senders need no
  // account.
  //
  // The length checks mirror ContactMessageLimits in lib/api. JS counts
  // UTF-16 code units (`string.length`), Postgres' char_length counts code
  // points, so Postgres never counts more than JS: whatever the API accepts
  // passes these checks. The minimum of 1 rejects empty strings; the API
  // also requires the values to be trimmed, which the database does not
  // enforce.
  //
  // created_at has no default: the application sets it from the Effect
  // clock, like the timestamps of users.
  yield* sql`
    CREATE TABLE contact_messages (
      id uuid NOT NULL,
      name text NOT NULL,
      email text NOT NULL,
      message text NOT NULL,
      created_at timestamptz NOT NULL,
      CONSTRAINT contact_messages_id_pkey PRIMARY KEY (id),
      CONSTRAINT contact_messages_name_check
        CHECK (char_length(name) BETWEEN 1 AND 100),
      CONSTRAINT contact_messages_email_check
        CHECK (char_length(email) BETWEEN 1 AND 254),
      CONSTRAINT contact_messages_message_check
        CHECK (char_length(message) BETWEEN 1 AND 5000)
    )
  `;

  // Serves the retention job:
  //
  //   DELETE FROM contact_messages WHERE created_at < $cutoff
  //
  // Nothing else reads the table by time or by any other column.
  yield* sql`
    CREATE INDEX contact_messages_created_at_idx
      ON contact_messages (created_at)
  `;
});
