import { Effect } from "effect";
import { SqlClient } from "effect/sql";

/**
 * Subblogs, their posts, and uploaded images ("media").
 *
 * Admins create and rename subblogs. Holders of `blogEditor:<slug>` write
 * the posts of that subblog and upload images for them. Posts are stored as
 * TipTap (ProseMirror) JSON, never as HTML, and images as bytes in Postgres.
 *
 * The checks mirror the contract (lib/api `domain/Blog.ts`, `Media.ts`).
 * Lengths are checked with char_length, which counts code points, while the
 * contract's `Schema.isMaxLength` counts UTF-16 code units (`string.length`):
 * the database never counts more than the API, so whatever the API accepts
 * passes. "Trimmed" in the contract is JS `String.prototype.trim`, which
 * removes Unicode whitespace; the checks here reject leading and trailing
 * ASCII whitespace only (space, \t, \n, \v, \f, \r), a subset, for the same
 * reason. `[[:space:]]` is not used: what it matches beyond ASCII depends on
 * the locale, and it could reject a value the API accepts.
 *
 * The timestamps have no defaults: the application sets them from the
 * Effect clock at millisecond precision, like the timestamps of users.
 */
export default Effect.gen(function* () {
  const sql = yield* SqlClient.SqlClient;

  // One row per subblog. id is generated by the application (UUID v4), like
  // users.id. slug is the public name in URLs and in the roles
  // `blogEditor:<slug>` (user_roles, 0012), with the same pattern and
  // length as there and as the contract's `BlogSlug`.
  //
  // slug is immutable: the roles refer to it by value, so renaming it would
  // silently disconnect (or, for a new subblog with the old slug, reconnect)
  // its editors. The application has no operation that changes it
  // (`UpdateBlogPayload` holds only title and description); the database
  // does not enforce this.
  //
  // created_by is the admin who created it; NULL for an operator in SQL and
  // for an account deleted since, like user_roles.granted_by. No index on
  // it: nothing reads blogs by creator, and the SET NULL on deleting a user
  // scans this tiny table.
  //
  // No index beyond the primary key and the unique slug: there are a
  // handful of rows, and every lookup is by slug.
  //
  // `\\t` etc. are escaped for the template literal: Postgres receives `\t`,
  // which its regular expressions read as a tab.
  yield* sql`
    CREATE TABLE blogs (
      id uuid NOT NULL,
      slug text NOT NULL,
      title text NOT NULL,
      description text NOT NULL,
      created_at timestamptz NOT NULL,
      created_by uuid NULL,
      updated_at timestamptz NOT NULL,
      CONSTRAINT blogs_id_pkey PRIMARY KEY (id),
      CONSTRAINT blogs_slug_key UNIQUE (slug),
      CONSTRAINT blogs_created_by_fkey FOREIGN KEY (created_by)
        REFERENCES users (id) ON DELETE SET NULL,
      CONSTRAINT blogs_slug_check
        CHECK (
          slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'
          AND char_length(slug) <= 64
        ),
      CONSTRAINT blogs_title_check
        CHECK (
          char_length(title) BETWEEN 1 AND 120
          AND title !~ '^[ \\t\\n\\v\\f\\r]|[ \\t\\n\\v\\f\\r]$'
        ),
      CONSTRAINT blogs_description_check
        CHECK (
          char_length(description) <= 1000
          AND description !~ '^[ \\t\\n\\v\\f\\r]|[ \\t\\n\\v\\f\\r]$'
        )
    )
  `;

  // One row per uploaded image. Rows are immutable: an upload is never
  // changed, only deleted, so `GET /media/:id` can be cached forever.
  //
  // content_type is detected by the application from the magic bytes, not
  // taken from the upload, and limited to the contract's
  // `MediaContentType`. byte_size is the size of data (at most 5 MiB, the
  // upload limit), stored so that listings need not read data;
  // octet_length on a bytea reads only its header, not the stored value.
  // sha256 must be the digest of data (Postgres' built-in sha256, 32
  // bytes), so it can be trusted for deduplication and integrity checks.
  //
  // scope says what the image belongs to: `blog:<slug>` for a subblog (the
  // slug as in blogs_slug_check, so at most 5 + 64 = 69 characters) or
  // `projects`. It is a label, not a foreign key: an image of a subblog is
  // uploaded before any post refers to it.
  //
  // uploaded_by is the editor; NULL for an account deleted since. No index
  // on it, like blogs.created_by.
  //
  // The index serves listing (and cleaning up) the uploads of one scope in
  // time order.
  yield* sql`
    CREATE TABLE media (
      id uuid NOT NULL,
      content_type text NOT NULL,
      data bytea NOT NULL,
      byte_size integer NOT NULL,
      sha256 bytea NOT NULL,
      scope text NOT NULL,
      uploaded_by uuid NULL,
      uploaded_at timestamptz NOT NULL,
      CONSTRAINT media_id_pkey PRIMARY KEY (id),
      CONSTRAINT media_uploaded_by_fkey FOREIGN KEY (uploaded_by)
        REFERENCES users (id) ON DELETE SET NULL,
      CONSTRAINT media_content_type_check
        CHECK (
          content_type IN (
            'image/png',
            'image/jpeg',
            'image/webp',
            'image/gif',
            'image/avif'
          )
        ),
      CONSTRAINT media_byte_size_check
        CHECK (
          byte_size BETWEEN 1 AND 5242880
          AND byte_size = octet_length(data)
        ),
      CONSTRAINT media_sha256_check CHECK (sha256 = sha256(data)),
      CONSTRAINT media_scope_check
        CHECK (
          scope ~ '^(blog:[a-z0-9]+(-[a-z0-9]+)*|projects)$'
          AND char_length(scope) <= 69
        )
    )
  `;

  yield* sql`
    CREATE INDEX media_scope_uploaded_at_idx
      ON media (scope, uploaded_at)
  `;

  // The element rules of the contract's post `tags`: every tag matches the
  // slug pattern and has at most 32 characters, no tag is NULL, and no tag
  // occurs twice. A check constraint cannot contain a subquery, so they live
  // in this function; blog_posts_tags_check calls it.
  //
  // count(DISTINCT tag) skips NULLs, so it equals the cardinality only
  // without NULLs and duplicates. A multidimensional array (or one with a
  // lower bound other than 1) is rejected too: tags is a plain list.
  //
  // IMMUTABLE is true (the result depends only on the argument), which a
  // function in a check constraint must be. Changing the rules means a new
  // migration that replaces the function and re-validates the constraint;
  // CREATE OR REPLACE alone would not check existing rows.
  yield* sql`
    CREATE FUNCTION blog_posts_tags_valid(tags text[]) RETURNS boolean
      LANGUAGE sql IMMUTABLE PARALLEL SAFE
      AS $$
        SELECT
          (cardinality(tags) = 0
            OR (array_ndims(tags) = 1 AND array_lower(tags, 1) = 1))
          AND count(DISTINCT tag) = cardinality(tags)
          AND coalesce(
            bool_and(
              tag ~ '^[a-z0-9]+(-[a-z0-9]+)*$' AND char_length(tag) <= 32
            ),
            true
          )
        FROM unnest(tags) AS tag
      $$
  `;

  // One row per post of a subblog. id is generated by the application.
  // Editors address a post by id (the slug can change), readers by
  // (blog, slug), hence the unique key; its index also serves the RESTRICT
  // check when a blog is deleted. A blog with posts cannot be deleted.
  //
  // slug follows the blog slug pattern, up to 128 characters (`PostSlug`).
  // title (1 to 200) and summary (0 to 500) are trimmed like blogs.title.
  //
  // content is the TipTap document. The contract's `Document` schema
  // validates it on the way in (it is the XSS defence); the database only
  // checks that the root is a `doc` node: an object with `"type": "doc"`
  // (`@>` on an array, a string or an object without `type` is false, not
  // NULL, which a check would let pass).
  //
  // cover_media_id is an image of media; deleting the image removes it as
  // cover. No index on it: images are deleted rarely, and the SET NULL then
  // scans the posts. author_id (the editor who created the post) and
  // updated_by (who saved it last) are NULL for accounts deleted since, and
  // have no index for the same reason as blogs.created_by.
  //
  // status decides visibility. published_at is the time of the first
  // publication: it is set by the first publish and kept when the post is
  // unpublished and published again, so a published post always has one
  // and a draft may. Public lists page by keyset over (published_at, id)
  // with the cursor carrying published_at as epoch milliseconds, so it must
  // have millisecond precision, like users.created_at (0011).
  //
  // version counts saves, for optimistic locking: an update names the
  // version it started from and increments it.
  yield* sql`
    CREATE TABLE blog_posts (
      id uuid NOT NULL,
      blog_id uuid NOT NULL,
      slug text NOT NULL,
      title text NOT NULL,
      summary text NOT NULL,
      tags text[] NOT NULL DEFAULT '{}',
      cover_media_id uuid NULL,
      content jsonb NOT NULL,
      status text NOT NULL,
      published_at timestamptz NULL,
      author_id uuid NULL,
      updated_by uuid NULL,
      created_at timestamptz NOT NULL,
      updated_at timestamptz NOT NULL,
      version integer NOT NULL DEFAULT 1,
      CONSTRAINT blog_posts_id_pkey PRIMARY KEY (id),
      CONSTRAINT blog_posts_blog_id_slug_key UNIQUE (blog_id, slug),
      CONSTRAINT blog_posts_blog_id_fkey FOREIGN KEY (blog_id)
        REFERENCES blogs (id) ON DELETE RESTRICT,
      CONSTRAINT blog_posts_cover_media_id_fkey FOREIGN KEY (cover_media_id)
        REFERENCES media (id) ON DELETE SET NULL,
      CONSTRAINT blog_posts_author_id_fkey FOREIGN KEY (author_id)
        REFERENCES users (id) ON DELETE SET NULL,
      CONSTRAINT blog_posts_updated_by_fkey FOREIGN KEY (updated_by)
        REFERENCES users (id) ON DELETE SET NULL,
      CONSTRAINT blog_posts_slug_check
        CHECK (
          slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'
          AND char_length(slug) <= 128
        ),
      CONSTRAINT blog_posts_title_check
        CHECK (
          char_length(title) BETWEEN 1 AND 200
          AND title !~ '^[ \\t\\n\\v\\f\\r]|[ \\t\\n\\v\\f\\r]$'
        ),
      CONSTRAINT blog_posts_summary_check
        CHECK (
          char_length(summary) <= 500
          AND summary !~ '^[ \\t\\n\\v\\f\\r]|[ \\t\\n\\v\\f\\r]$'
        ),
      CONSTRAINT blog_posts_tags_check
        CHECK (cardinality(tags) <= 10 AND blog_posts_tags_valid(tags)),
      CONSTRAINT blog_posts_content_check
        CHECK (content @> '{"type": "doc"}'),
      CONSTRAINT blog_posts_status_check
        CHECK (status IN ('draft', 'published')),
      CONSTRAINT blog_posts_published_at_check
        CHECK (status = 'draft' OR published_at IS NOT NULL),
      CONSTRAINT blog_posts_published_at_milliseconds_check
        CHECK (published_at = date_trunc('milliseconds', published_at)),
      CONSTRAINT blog_posts_version_check CHECK (version >= 1)
    )
  `;

  // The published posts of one subblog, newest first, by keyset:
  //
  //   WHERE blog_id = $blog AND status = 'published'
  //     AND (published_at, id) < ($at, $id)
  //   ORDER BY published_at DESC, id DESC LIMIT $n
  //
  // Also serves the subblog overview (count and latest published_at).
  yield* sql`
    CREATE INDEX blog_posts_blog_id_published_at_id_idx
      ON blog_posts (blog_id, published_at DESC, id DESC)
      WHERE status = 'published'
  `;

  // The same over all subblogs (`GET /posts`).
  yield* sql`
    CREATE INDEX blog_posts_published_at_id_idx
      ON blog_posts (published_at DESC, id DESC)
      WHERE status = 'published'
  `;

  // The tag filter of both lists: `tags @> ARRAY[$tag]`.
  yield* sql`
    CREATE INDEX blog_posts_tags_idx ON blog_posts USING gin (tags)
  `;

  // The editors' list of a subblog's posts, all statuses, last saved first.
  yield* sql`
    CREATE INDEX blog_posts_blog_id_updated_at_idx
      ON blog_posts (blog_id, updated_at DESC)
  `;
});
