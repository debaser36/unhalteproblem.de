import { Effect } from "effect";
import { SqlClient } from "effect/sql";

/**
 * Categories of subblogs and posts, the stored word count of posts, and the
 * audit actions of managing categories.
 *
 * There is one list of categories, shared by subblogs and posts. Every
 * subblog and every post has exactly one main category (required) and up to
 * three extra categories, all distinct, the main one not among them.
 * Editors create categories implicitly by naming one that does not exist
 * yet; admins rename them (the slug follows the name), merge one into
 * another, and delete unused ones.
 *
 * The database enforces that the main category exists and that an extra
 * category is listed at most once per subblog or post (the primary keys of
 * the join tables). It does not enforce the cap of three extras, nor that
 * the main category is not also an extra: both need a look at other rows (a
 * trigger), and the application validates them anyway, in the contract and
 * in the commands that replace a post's or subblog's categories in one
 * transaction. A merge must keep them too (see blog_extra_categories).
 *
 * The text checks follow blogs (0013), see there: lengths in code points,
 * no leading or trailing ASCII whitespace. The timestamps have no defaults:
 * the application sets them from the Effect clock at millisecond precision.
 * Only the seeded presets take theirs from the database clock.
 *
 * Four new audit actions, written by the category commands in their
 * transaction:
 *
 * - `category_created`: an editor or admin introduced a new category
 *   (editors implicitly, by naming one). detail is its slug.
 * - `category_renamed`: an admin renamed a category. detail is the new slug.
 * - `category_merged`: an admin merged a category into another. detail is
 *   the slug of the source, the category that no longer exists.
 * - `category_deleted`: an admin deleted an unused category. detail is its
 *   slug.
 *
 * This replaces audit_log_action_check (0017) under the same name, the same
 * way 0015 did; see there for why it is one statement and validated right
 * away. Adding an action still means a new migration that replaces it again.
 */
export default Effect.gen(function* () {
  const sql = yield* SqlClient.SqlClient;

  // One row per category. id is generated by the application (UUID v4),
  // like blogs.id. name is what readers see: trimmed, 1 to 48 characters
  // (the contract's `CategoryName`). slug is the public name in URLs (the
  // category filter), derived from the name by the application, with the
  // pattern of blogs.slug and at most 48 characters (`CategorySlug`).
  //
  // Unlike blogs.slug, slug is not immutable: a rename sets a new slug
  // derived from the new name. Nothing refers to categories by slug (the
  // join tables and main_category_id refer to id), so only links already
  // shared break. Two names that derive the same slug (`Data & AI` and
  // `data and ai`) collide on categories_slug_key; the application catches
  // the unique violation on that name, so keep it stable. Names themselves
  // are not unique: the slug is what has to be.
  //
  // created_by is the editor or admin who created it; NULL for the presets
  // below, for an operator in SQL, and for an account deleted since, like
  // blogs.created_by. No index on it, for the same reason as there.
  //
  // No index beyond the primary key and the unique slug: the list is short,
  // and lookups are by id or slug. Lists sort by name in memory.
  //
  // `\\t` etc. are escaped for the template literal, as in 0013.
  yield* sql`
    CREATE TABLE categories (
      id uuid NOT NULL,
      slug text NOT NULL,
      name text NOT NULL,
      created_at timestamptz NOT NULL,
      created_by uuid NULL,
      CONSTRAINT categories_id_pkey PRIMARY KEY (id),
      CONSTRAINT categories_slug_key UNIQUE (slug),
      CONSTRAINT categories_created_by_fkey FOREIGN KEY (created_by)
        REFERENCES users (id) ON DELETE SET NULL,
      CONSTRAINT categories_slug_check
        CHECK (
          slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'
          AND char_length(slug) <= 48
        ),
      CONSTRAINT categories_name_check
        CHECK (
          char_length(name) BETWEEN 1 AND 48
          AND name !~ '^[ \\t\\n\\v\\f\\r]|[ \\t\\n\\v\\f\\r]$'
        )
    )
  `;

  // The presets, so that editors have something to choose from on the
  // first post. They are ordinary rows: admins may rename, merge or delete
  // them like any other category, except `miscellaneous` while the
  // backfilled subblogs and posts below still use it. The slugs are what
  // the application would derive from the names.
  //
  // created_at is the time of the migration, truncated to milliseconds like
  // the timestamps the application writes.
  yield* sql`
    INSERT INTO categories (id, slug, name, created_at, created_by)
    SELECT gen_random_uuid(), preset.slug, preset.name,
      date_trunc('milliseconds', now()), NULL
    FROM (
      VALUES
        ('programming', 'Programming'),
        ('web-development', 'Web Development'),
        ('systems-and-infrastructure', 'Systems & Infrastructure'),
        ('security', 'Security'),
        ('data-and-ai', 'Data & AI'),
        ('tools-and-workflow', 'Tools & Workflow'),
        ('open-source', 'Open Source'),
        ('career', 'Career'),
        ('personal', 'Personal'),
        ('miscellaneous', 'Miscellaneous')
    ) AS preset (slug, name)
  `;

  // The main category of a subblog. Added without NOT NULL, filled with
  // `miscellaneous` for the subblogs that exist already, then made
  // required: there is no default, the application always names one.
  //
  // RESTRICT: a category in use cannot be deleted; a merge re-points its
  // users first. The index serves that check and the subblog list filtered
  // by category.
  yield* sql`
    ALTER TABLE blogs
      ADD COLUMN main_category_id uuid NULL,
      ADD CONSTRAINT blogs_main_category_id_fkey FOREIGN KEY (main_category_id)
        REFERENCES categories (id) ON DELETE RESTRICT
  `;
  yield* sql`
    UPDATE blogs
    SET main_category_id = (
      SELECT id FROM categories WHERE slug = 'miscellaneous'
    )
    WHERE main_category_id IS NULL
  `;
  yield* sql`
    ALTER TABLE blogs ALTER COLUMN main_category_id SET NOT NULL
  `;
  yield* sql`
    CREATE INDEX blogs_main_category_id_idx ON blogs (main_category_id)
  `;

  // The same for posts. A post's categories are its own: they do not follow
  // its subblog's, and the backfill sets them independently.
  yield* sql`
    ALTER TABLE blog_posts
      ADD COLUMN main_category_id uuid NULL,
      ADD CONSTRAINT blog_posts_main_category_id_fkey
        FOREIGN KEY (main_category_id)
        REFERENCES categories (id) ON DELETE RESTRICT
  `;
  yield* sql`
    UPDATE blog_posts
    SET main_category_id = (
      SELECT id FROM categories WHERE slug = 'miscellaneous'
    )
    WHERE main_category_id IS NULL
  `;
  yield* sql`
    ALTER TABLE blog_posts ALTER COLUMN main_category_id SET NOT NULL
  `;
  yield* sql`
    CREATE INDEX blog_posts_main_category_id_idx
      ON blog_posts (main_category_id)
  `;

  // The extra categories of a subblog, one row per (subblog, category).
  // Deleting the subblog deletes its rows; a category in use cannot be
  // deleted (RESTRICT), as for main_category_id.
  //
  // A merge of `source` into `target` re-points the rows of source, except
  // where the subblog already has target (as an extra: the primary key
  // would reject the duplicate; as main: the main-not-extra rule), deletes
  // the rest of source's rows, sets main_category_id from source to target,
  // removes target from the extras of the subblogs whose main it became,
  // and finally deletes source. The same goes for blog_post_extra_categories.
  // The cap of three cannot be exceeded by a merge: it never adds an extra.
  //
  // The primary key serves reading a subblog's extras. The index on
  // (category_id, blog_id) serves the filter by category, the merge, and
  // the RESTRICT check.
  yield* sql`
    CREATE TABLE blog_extra_categories (
      blog_id uuid NOT NULL,
      category_id uuid NOT NULL,
      CONSTRAINT blog_extra_categories_blog_id_category_id_pkey
        PRIMARY KEY (blog_id, category_id),
      CONSTRAINT blog_extra_categories_blog_id_fkey FOREIGN KEY (blog_id)
        REFERENCES blogs (id) ON DELETE CASCADE,
      CONSTRAINT blog_extra_categories_category_id_fkey
        FOREIGN KEY (category_id)
        REFERENCES categories (id) ON DELETE RESTRICT
    )
  `;
  yield* sql`
    CREATE INDEX blog_extra_categories_category_id_blog_id_idx
      ON blog_extra_categories (category_id, blog_id)
  `;

  // The extra categories of a post, like blog_extra_categories. Deleting the
  // post deletes its rows.
  //
  // The post lists filter by "main or extra category is X":
  //
  //   WHERE p.main_category_id = $c
  //      OR EXISTS (SELECT 1 FROM blog_post_extra_categories e
  //                 WHERE e.post_id = p.id AND e.category_id = $c)
  //
  // blog_posts_main_category_id_idx serves the first half, the primary key
  // the second, and blog_post_extra_categories_category_id_post_id_idx the
  // same filter written as a UNION of both sides, the merge, and the
  // RESTRICT check.
  yield* sql`
    CREATE TABLE blog_post_extra_categories (
      post_id uuid NOT NULL,
      category_id uuid NOT NULL,
      CONSTRAINT blog_post_extra_categories_post_id_category_id_pkey
        PRIMARY KEY (post_id, category_id),
      CONSTRAINT blog_post_extra_categories_post_id_fkey FOREIGN KEY (post_id)
        REFERENCES blog_posts (id) ON DELETE CASCADE,
      CONSTRAINT blog_post_extra_categories_category_id_fkey
        FOREIGN KEY (category_id)
        REFERENCES categories (id) ON DELETE RESTRICT
    )
  `;
  yield* sql`
    CREATE INDEX blog_post_extra_categories_category_id_post_id_idx
      ON blog_post_extra_categories (category_id, post_id)
  `;

  // The number of words of a post's text, stored so that lists can sort by
  // reading time and page by keyset over (word_count, id) without walking
  // every document. Until now BlogRepository counted it per query with the
  // expression in blog_posts_set_word_count below. A word is a maximal run
  // of non-whitespace in a `text` node of the TipTap document; `strict`
  // keeps `$.**` from unwrapping arrays and counting words twice.
  //
  // The database keeps it in sync, not the application: the trigger sets
  // it from content on every insert and on every update that names content
  // (or word_count) in its SET list, so it cannot go stale and cannot be
  // set to anything else. The application treats it as read-only
  // (`Model.GeneratedByDb`) and never writes it. The default 0 only exists
  // so that statements need not name the column; the trigger overwrites it
  // before the row is stored. An update that does not name content keeps
  // the count, which is still right since the content is unchanged.
  //
  // `\\s` is escaped for the template literal: Postgres receives `\s`, as in
  // BlogRepository.
  yield* sql`
    ALTER TABLE blog_posts
      ADD COLUMN word_count integer NOT NULL DEFAULT 0,
      ADD CONSTRAINT blog_posts_word_count_check CHECK (word_count >= 0)
  `;
  yield* sql`
    CREATE FUNCTION blog_posts_set_word_count() RETURNS trigger
      LANGUAGE plpgsql
      AS $$
        BEGIN
          NEW.word_count := (
            SELECT count(*)::int
            FROM jsonb_path_query(NEW.content, 'strict $.**.text') AS t(text),
                 regexp_split_to_table(t.text #>> '{}', '\\s+') AS w(word)
            WHERE w.word <> ''
          );
          RETURN NEW;
        END
      $$
  `;
  yield* sql`
    CREATE TRIGGER blog_posts_set_word_count_trigger
      BEFORE INSERT OR UPDATE OF content, word_count ON blog_posts
      FOR EACH ROW EXECUTE FUNCTION blog_posts_set_word_count()
  `;
  // The backfill: naming content fires the trigger for every existing post
  // (the column was 0 for all of them). It changes nothing else: version
  // and updated_at stay, a recount is not a save.
  yield* sql`
    UPDATE blog_posts SET content = content
  `;

  // No indexes for the new sort orders of the post lists (by title, last
  // update, author, category or word count, over the published posts). This
  // is a personal website with at most a few hundred posts: Postgres reads
  // the published ones and sorts them in memory in well under a
  // millisecond, while every index would be written on every save. Sorts by
  // author or category are by a name in another table (users, categories),
  // which no index on blog_posts can serve anyway, and each sort would need
  // one index per list (all subblogs, one subblog) and direction. The
  // default order, newest first, keeps its indexes from 0013. Add an index
  // in a new migration once a plan shows a sort is slow.

  // Only widens the old check, so every existing row satisfies it.
  yield* sql`
    ALTER TABLE audit_log
      DROP CONSTRAINT audit_log_action_check,
      ADD CONSTRAINT audit_log_action_check
        CHECK (
          action IN (
            'login',
            'logout',
            'login_refused',
            'role_granted',
            'role_revoked',
            'user_restricted',
            'restriction_lifted',
            'account_deleted',
            'outbox_retried',
            'contact_message_deleted',
            'blog_created',
            'blog_updated',
            'post_deleted',
            'project_created',
            'project_updated',
            'project_deleted',
            'blog_request_approved',
            'blog_request_rejected',
            'category_created',
            'category_renamed',
            'category_merged',
            'category_deleted'
          )
        )
  `;
});
