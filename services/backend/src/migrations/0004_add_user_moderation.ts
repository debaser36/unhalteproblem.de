import { Effect } from "effect";
import { SqlClient } from "effect/sql";

/**
 * User moderation by admins: who granted a role, a log of role grants and
 * revocations, and account restrictions.
 *
 * superAdmins grant and revoke roles, admins restrict (block) accounts with
 * a note and lift restrictions. A restricted user stays blocked until an
 * admin lifts the restriction. Actors are identified by `users.id`.
 */
export default Effect.gen(function* () {
  const sql = yield* SqlClient.SqlClient;

  // The user who granted the role. NULL means the system (normalUser at
  // registration) or an operator in SQL, and also an actor deleted since:
  // deleting a user keeps the roles they granted.
  //
  // Nullable without a default, so existing rows need no rewrite. No index:
  // nothing reads roles by granter, and deleting a user only scans this
  // small table for the SET NULL.
  yield* sql`ALTER TABLE user_roles ADD COLUMN granted_by uuid NULL`;
  yield* sql`
    ALTER TABLE user_roles
      ADD CONSTRAINT user_roles_granted_by_fkey FOREIGN KEY (granted_by)
        REFERENCES users (id) ON DELETE SET NULL
  `;

  // Append-only log of role grants and revocations: user_roles only holds
  // the current state. The application inserts a row in the transaction
  // that changes user_roles; rows are never updated or deleted, except
  // together with the user. changed_by is NULL for the system and for
  // operators, like granted_by.
  //
  // role and change are limited by check constraints. role takes the same
  // list as user_roles_role_check: a migration that adds a role changes
  // both. Removing a role from this list fails while the log still has rows
  // for it, since re-adding the check validates existing rows.
  //
  // changed_at has no default: the application sets it from the Effect
  // clock, like the timestamps of users.
  //
  // The index serves the details page, which reads one user's log in time
  // order, and the cascading delete. The actor columns have no index, for
  // the same reason as user_roles.granted_by.
  yield* sql`
    CREATE TABLE user_role_changes (
      id bigint GENERATED ALWAYS AS IDENTITY,
      user_id uuid NOT NULL,
      role text NOT NULL,
      change text NOT NULL,
      changed_by uuid NULL,
      changed_at timestamptz NOT NULL,
      CONSTRAINT user_role_changes_id_pkey PRIMARY KEY (id),
      CONSTRAINT user_role_changes_user_id_fkey FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE CASCADE,
      CONSTRAINT user_role_changes_changed_by_fkey FOREIGN KEY (changed_by)
        REFERENCES users (id) ON DELETE SET NULL,
      CONSTRAINT user_role_changes_role_check
        CHECK (role IN ('normalUser', 'admin', 'superAdmin')),
      CONSTRAINT user_role_changes_change_check
        CHECK (change IN ('granted', 'revoked'))
    )
  `;
  yield* sql`
    CREATE INDEX user_role_changes_user_id_changed_at_idx
      ON user_role_changes (user_id, changed_at)
  `;

  // Every role granted so far starts the log, as granted by the system at
  // its granted_at. Earlier revocations were plain DELETEs and are lost.
  yield* sql`
    INSERT INTO user_role_changes (user_id, role, change, changed_by, changed_at)
    SELECT user_id, role, 'granted', NULL, granted_at FROM user_roles
    ORDER BY granted_at, user_id, role
  `;

  // Restrictions, active and lifted: a lift updates the row instead of
  // deleting it, so the table is also the history. id is generated by the
  // application (UUID v4), like users.id.
  //
  // restricted_by is nullable only so that deleting the actor keeps the
  // history; the application always sets it. lifted_at marks a lift.
  // lifted_by is NULL after its actor was deleted, and lift_note is
  // optional. Notes are limited to 2000 characters, and an empty note is
  // rejected (a missing lift note is NULL).
  //
  // user_restrictions_lifted_check rejects a lifter or lift note without a
  // lift, and a lift before the restriction.
  //
  // The timestamps have no default: the application sets them from the
  // Effect clock.
  yield* sql`
    CREATE TABLE user_restrictions (
      id uuid NOT NULL,
      user_id uuid NOT NULL,
      note text NOT NULL,
      restricted_by uuid NULL,
      restricted_at timestamptz NOT NULL,
      lifted_at timestamptz NULL,
      lifted_by uuid NULL,
      lift_note text NULL,
      CONSTRAINT user_restrictions_id_pkey PRIMARY KEY (id),
      CONSTRAINT user_restrictions_user_id_fkey FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE CASCADE,
      CONSTRAINT user_restrictions_restricted_by_fkey FOREIGN KEY (restricted_by)
        REFERENCES users (id) ON DELETE SET NULL,
      CONSTRAINT user_restrictions_lifted_by_fkey FOREIGN KEY (lifted_by)
        REFERENCES users (id) ON DELETE SET NULL,
      CONSTRAINT user_restrictions_note_check
        CHECK (char_length(note) BETWEEN 1 AND 2000),
      CONSTRAINT user_restrictions_lift_note_check
        CHECK (char_length(lift_note) BETWEEN 1 AND 2000),
      CONSTRAINT user_restrictions_lifted_check
        CHECK (
          (lifted_at IS NOT NULL OR (lifted_by IS NULL AND lift_note IS NULL))
          AND (lifted_at IS NULL OR lifted_at >= restricted_at)
        )
    )
  `;

  // At most one active restriction per user. A partial unique index, not a
  // constraint, so the name has no table constraint behind it, but a
  // violation still reports it as the constraint. It also serves the check
  // "is this user restricted?" on every authenticated request.
  yield* sql`
    CREATE UNIQUE INDEX user_restrictions_active_key
      ON user_restrictions (user_id)
      WHERE lifted_at IS NULL
  `;

  // A user's history, newest first (read backwards), and the cascading
  // delete; the partial index above only covers active rows. The actor
  // columns have no index, for the same reason as user_roles.granted_by.
  yield* sql`
    CREATE INDEX user_restrictions_user_id_restricted_at_idx
      ON user_restrictions (user_id, restricted_at)
  `;
});
