import { Effect } from "effect";
import { SqlClient } from "effect/sql";

/**
 * Requests for a subblog, and the audit actions of deciding them.
 *
 * Any logged-in user asks for a subblog with a title and a description. An
 * admin or superAdmin approves it (which creates the subblog and grants the
 * requester `blogEditor:<slug>`) or rejects it with an optional reason, and
 * the requester can withdraw a pending one. A user has at most one pending
 * request.
 *
 * The text checks follow blogs (0013), see there: lengths in code points,
 * no leading or trailing ASCII whitespace. The timestamps have no defaults:
 * the application sets them from the Effect clock at millisecond
 * precision.
 *
 * Two new audit actions, written by the blog request commands in their
 * transaction:
 *
 * - `blog_request_approved`: an admin approved a request. target is the
 *   requester, detail the slug of the created subblog.
 * - `blog_request_rejected`: an admin rejected a request. target is the
 *   requester. No detail: the reason is free text, which the log never
 *   keeps.
 *
 * Requesting and withdrawing are not audited: the event log has them.
 *
 * This replaces audit_log_action_check (0016) under the same name, the same
 * way 0015 did; see there for why it is one statement and validated right
 * away. Adding an action still means a new migration that replaces it again.
 */
export default Effect.gen(function* () {
  const sql = yield* SqlClient.SqlClient;

  // One row per request. id is generated by the application (UUID v4),
  // like blogs.id. Rows are never deleted by the application: a decided
  // request stays as the requester's history.
  //
  // requester_id is the user who asked. Users are soft-deleted (0010), so
  // the CASCADE fires only when an operator deletes a user in SQL.
  //
  // title and description are what the requester proposed, with the limits
  // of blogs.title and blogs.description; the subblog created on approval
  // gets them as they are, with the slug the moderator chooses.
  //
  // status is `pending` until the request is decided: `approved` or
  // `rejected` by a moderator, or `withdrawn` by the requester. Exactly the
  // decided requests have decided_at (blog_requests_status_decided_at_check),
  // and a pending one has no decided_by. decided_by is the moderator, or the
  // requester for a withdrawal; it is not required for decided requests,
  // since deleting the account sets it to NULL.
  //
  // reason is the optional rejection reason, which the requester sees:
  // trimmed, 1 to 1000 characters, and only on rejected requests (no reason
  // is NULL, not an empty string).
  //
  // blog_id is the subblog created by the approval, and only approved
  // requests have one. It is not required for them: deleting the subblog
  // sets it to NULL, and the request stays approved.
  //
  // No index on decided_by or blog_id: nothing reads requests by them, and
  // the SET NULL on deleting a user or a subblog scans this small table,
  // like blogs.created_by.
  //
  // `\\t` etc. are escaped for the template literal, as in 0013.
  yield* sql`
    CREATE TABLE blog_requests (
      id uuid NOT NULL,
      requester_id uuid NOT NULL,
      title text NOT NULL,
      description text NOT NULL,
      status text NOT NULL,
      created_at timestamptz NOT NULL,
      decided_at timestamptz NULL,
      decided_by uuid NULL,
      reason text NULL,
      blog_id uuid NULL,
      CONSTRAINT blog_requests_id_pkey PRIMARY KEY (id),
      CONSTRAINT blog_requests_requester_id_fkey FOREIGN KEY (requester_id)
        REFERENCES users (id) ON DELETE CASCADE,
      CONSTRAINT blog_requests_decided_by_fkey FOREIGN KEY (decided_by)
        REFERENCES users (id) ON DELETE SET NULL,
      CONSTRAINT blog_requests_blog_id_fkey FOREIGN KEY (blog_id)
        REFERENCES blogs (id) ON DELETE SET NULL,
      CONSTRAINT blog_requests_title_check
        CHECK (
          char_length(title) BETWEEN 1 AND 120
          AND title !~ '^[ \\t\\n\\v\\f\\r]|[ \\t\\n\\v\\f\\r]$'
        ),
      CONSTRAINT blog_requests_description_check
        CHECK (
          char_length(description) <= 1000
          AND description !~ '^[ \\t\\n\\v\\f\\r]|[ \\t\\n\\v\\f\\r]$'
        ),
      CONSTRAINT blog_requests_status_check
        CHECK (status IN ('pending', 'approved', 'rejected', 'withdrawn')),
      CONSTRAINT blog_requests_reason_check
        CHECK (
          char_length(reason) BETWEEN 1 AND 1000
          AND reason !~ '^[ \\t\\n\\v\\f\\r]|[ \\t\\n\\v\\f\\r]$'
        ),
      CONSTRAINT blog_requests_status_decided_at_check
        CHECK ((status = 'pending') = (decided_at IS NULL)),
      CONSTRAINT blog_requests_status_decided_by_check
        CHECK (status <> 'pending' OR decided_by IS NULL),
      CONSTRAINT blog_requests_status_reason_check
        CHECK (status = 'rejected' OR reason IS NULL),
      CONSTRAINT blog_requests_status_blog_id_check
        CHECK (status = 'approved' OR blog_id IS NULL)
    )
  `;

  // At most one pending request per user. The application inserts and
  // catches the unique violation on this name, so a concurrent second
  // request fails too; keep the name stable.
  yield* sql`
    CREATE UNIQUE INDEX blog_requests_one_pending_per_user
      ON blog_requests (requester_id)
      WHERE status = 'pending'
  `;

  // The requester's own requests, newest first:
  //
  //   WHERE requester_id = $user ORDER BY created_at DESC, id DESC LIMIT $n
  //
  // Also serves the CASCADE on deleting a user.
  yield* sql`
    CREATE INDEX blog_requests_requester_id_created_at_id_idx
      ON blog_requests (requester_id, created_at DESC, id DESC)
  `;

  // The admins' list of one status (mostly the pending ones), newest first:
  //
  //   WHERE status = $status ORDER BY created_at DESC, id DESC LIMIT $n
  //
  // Not partial on `pending`: the status is a parameter, which a generic
  // plan cannot match against a partial index's predicate. The list over
  // all statuses has no index of its own and sorts; the table stays small.
  yield* sql`
    CREATE INDEX blog_requests_status_created_at_id_idx
      ON blog_requests (status, created_at DESC, id DESC)
  `;

  // Only widens the old check, so every existing row satisfies it.
  yield* sql`
    ALTER TABLE audit_log
      DROP CONSTRAINT audit_log_action_check,
      ADD CONSTRAINT audit_log_action_check
        CHECK (
          action IN (
            'login',
            'logout',
            'login_refused',
            'role_granted',
            'role_revoked',
            'user_restricted',
            'restriction_lifted',
            'account_deleted',
            'outbox_retried',
            'contact_message_deleted',
            'blog_created',
            'blog_updated',
            'post_deleted',
            'project_created',
            'project_updated',
            'project_deleted',
            'blog_request_approved',
            'blog_request_rejected'
          )
        )
  `;
});
