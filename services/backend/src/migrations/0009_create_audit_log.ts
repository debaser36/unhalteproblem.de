import { Effect } from "effect";
import { SqlClient } from "effect/sql";

/**
 * An append-only record of who did what to whom: logins and logouts, role
 * changes, restrictions and account deletions.
 *
 * The application inserts a row in the same transaction as the action it
 * records; logins and logouts get their own transaction. Rows are never
 * updated, and only the retention job deletes them.
 *
 * The table must never hold personal data: no names, e-mail addresses,
 * notes, IP addresses. It is kept for the retention period (one year by
 * default) and outlives the users it mentions, so it holds ids and short
 * non-personal qualifiers only. A job purges old rows with
 * `DELETE FROM audit_log WHERE at < $cutoff`.
 */
export default Effect.gen(function* () {
  const sql = yield* SqlClient.SqlClient;

  // One row per audited action.
  //
  // action is limited by a check constraint, like the role columns of
  // user_roles: a migration that adds an action replaces
  // audit_log_action_check. Removing an action from the list fails while
  // the log still has rows for it, since re-adding the check validates
  // existing rows.
  //
  // actor_id is the user who acted. It is NULL for the system and for
  // operators, like user_roles.granted_by. target_id is the user it was
  // done to; it equals actor_id for login, logout and account_deleted.
  // Both hold users.id.
  //
  // There are no foreign keys, on purpose: the log must outlive users, and
  // it must never block deleting one (account_deleted is itself an entry
  // about a user that no longer exists). The ids simply stop resolving.
  //
  // detail is a short qualifier, such as the role name of role_granted and
  // role_revoked. It must not be personal data (see above). The length
  // check rejects empty strings (a missing detail is NULL) and keeps the
  // column from being used for free text.
  //
  // at has no default: the application sets it from the Effect clock, like
  // the timestamps of users. id is generated by the database (ALWAYS, so an
  // insert cannot set it) and increases with each insert; the admin view
  // pages by it.
  yield* sql`
    CREATE TABLE audit_log (
      id bigint GENERATED ALWAYS AS IDENTITY,
      at timestamptz NOT NULL,
      action text NOT NULL,
      actor_id uuid NULL,
      target_id uuid NULL,
      detail text NULL,
      CONSTRAINT audit_log_id_pkey PRIMARY KEY (id),
      CONSTRAINT audit_log_action_check
        CHECK (
          action IN (
            'login',
            'logout',
            'login_refused',
            'role_granted',
            'role_revoked',
            'user_restricted',
            'restriction_lifted',
            'account_deleted'
          )
        ),
      CONSTRAINT audit_log_detail_check
        CHECK (char_length(detail) BETWEEN 1 AND 100)
    )
  `;

  // Serves the retention job:
  //
  //   DELETE FROM audit_log WHERE at < $cutoff
  //
  // Without it, every purge would scan the whole log, which only grows.
  yield* sql`
    CREATE INDEX audit_log_at_idx
      ON audit_log (at)
  `;

  // Serves the admin view of one user's history, paged by keyset on id:
  //
  //   SELECT * FROM audit_log
  //   WHERE target_id = $user AND id > $lastId
  //   ORDER BY id
  //   LIMIT $n
  //
  // With target_id first, the index finds the user's rows, and id second
  // returns them already in order, so LIMIT stops after n rows and the next
  // page starts at its place in the index. id is unique, so the order is
  // total and the pages have no gaps or repeats. It is partial because
  // rows without a target are never read by user, which keeps the index
  // smaller.
  yield* sql`
    CREATE INDEX audit_log_target_id_idx
      ON audit_log (target_id, id)
      WHERE target_id IS NOT NULL
  `;
});
